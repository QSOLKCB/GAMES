// Bundle data/*.TXT into data/packed.js so the game can open from file://,
// where browsers refuse to read loose files. The .TXT files stay the source of
// truth: tests fail if packed.js is out of date. Usage: node scripts/pack-data.js
"use strict";
const fs = require("node:fs");
const path = require("node:path");
const dir = path.join(__dirname, "..", "data");
const FILES = ["SHIPS.TXT", "EQUIPMENT.TXT", "COMMODITIES.TXT", "OUTLAWS.TXT", "MISSIONS.TXT", "PILOTNAMES.TXT"];
function packedSource() {
  const texts = Object.fromEntries(FILES.map((name) => [name, fs.readFileSync(path.join(dir, name), "utf8")]));
  return `/* Generated by scripts/pack-data.js from data/*.TXT. Edit the .TXT files, then rerun the script. */\n` +
    `(function (root) {\n  "use strict";\n  root.CorsairData = Object.freeze(${JSON.stringify(texts, null, 2).replace(/\n/g, "\n  ")});\n})(typeof globalThis !== "undefined" ? globalThis : this);\n`;
}
module.exports = { FILES, packedSource };
if (require.main === module) {
  fs.writeFileSync(path.join(dir, "packed.js"), packedSource());
  console.log(`Packed ${FILES.length} data files into data/packed.js`);
}
